// Generates migrations/0002_seed.sql from the roster extracted out of the
// church's spreadsheet. Re-runnable: it rewrites the file from scratch.
//
//   node seed/build-seed.cjs
//
// Two D1 limits shape the output and both were hit the hard way:
//   * a compound SELECT (UNION ALL) accepts far fewer terms than stock SQLite,
//     so rows go in as individual statements;
//   * multi-row VALUES lists are chunked for the same reason.
// Every insert is OR IGNORE, so applying this twice changes nothing.
const fs = require('fs');

const OUT = __dirname + '/../migrations/0002_seed.sql';
const d = JSON.parse(fs.readFileSync(__dirname + '/roster.json', 'utf8'));

const q = (x) => (x == null ? 'NULL' : "'" + String(x).replace(/'/g, "''") + "'");
const CHUNK = 20;

/** Emit an INSERT per chunk of rows, so no single statement is oversized. */
function chunked(table, cols, rows) {
  const out = [];
  for (let i = 0; i < rows.length; i += CHUNK) {
    out.push(
      `INSERT OR IGNORE INTO ${table} (${cols}) VALUES\n` +
        rows.slice(i, i + CHUNK).map((r) => '  (' + r + ')').join(',\n') + ';',
    );
  }
  return out.join('\n');
}

const L = [];
L.push('-- Seed data for the Bream Church system.');
L.push('-- Generated by seed/build-seed.cjs from "September-November 2026.xlsx",');
L.push('-- the rota the church is running today. Every insert is OR IGNORE.');
L.push('');

// ---- roles ---------------------------------------------------------------
const ROLES = [
  ['preacher', 'Preacher', 'Preacher', 10, 1, 1, 0],
  ['service_leader', 'Service leader', 'Leader', 20, 1, 1, 0],
  ['worship_leader', 'Worship leader', 'Music', 30, 1, 1, 0],
  ['reader', 'Reader', 'Readers', 40, 2, 2, 0],
  // The operator's spec said 2; the rota consistently allocates 4. Settled as
  // "2 minimum, 4 ideal" — below 2 is a gap, 2-3 is merely untidy.
  ['prayer_ministry', 'Prayer ministry', 'Prayer Ministry', 50, 2, 4, 0],
  ['welcome_team', 'Welcome team', 'Welcome', 60, 2, 2, 0],
  ['steward', 'Steward', 'Steward', 70, 1, 1, 0],
  ['tea_coffee', 'Tea and coffee', 'Tea/Coffee', 80, 2, 2, 0],
  ['children_rec_yr5', 'Children: Rec to Yr 5 (4-10yr)', 'Rec - Yr 5 (4yr-10yr)', 90, 2, 2, 0],
  ['children_yr6_14', 'Children: Yr 6 and 10-14yrs', 'Yr 6 + 10-14yrs', 100, 2, 2, 0],
  ['sound_desk', 'Sound desk', 'Sound', 110, 1, 1, 0],
  ['computer', 'Computer', 'Laptop', 120, 1, 1, 0],
  ['communion_preside', 'Communion preside', 'Preside', 130, 1, 1, 1],
  ['communion_distribution', 'Communion distribution', 'Communion distribution', 140, 4, 4, 1],
];
L.push('-- The fourteen roles. min_needed vs ideal_needed is what lets prayer ministry');
L.push('-- warn below 2 while still aiming for 4. communion_only roles do not exist at all');
L.push('-- on a non-communion service, rather than sitting there permanently unfilled.');
L.push(chunked('roles', 'key,name,sheet_heading,sort_order,min_needed,ideal_needed,communion_only',
  ROLES.map((r) => [q(r[0]), q(r[1]), q(r[2]), r[3], r[4], r[5], r[6]].join(','))));
L.push('');

// ---- service types, rooms -------------------------------------------------
const TYPES = [
  ['Worship', 0, '10:30'], ['Holy Communion', 1, '10:30'], ['Messy Church', 0, '16:00'],
  ['LIFT', 0, '18:00'], ['Said Holy Communion', 1, '09:00'], ['Carol service', 0, '18:00'],
  ['Other', 0, null],
];
L.push(chunked('service_types', 'name,is_communion,default_time',
  TYPES.map((t) => [q(t[0]), t[1], q(t[2])].join(','))));
L.push('');
L.push(chunked('rooms', 'name,sort_order',
  [['Main church', 10], ['Church Centre', 20], ['Prayer room', 30], ['Sofa room', 40]]
    .map((r) => `${q(r[0])},${r[1]}`)));
L.push('');

// ---- people ---------------------------------------------------------------
L.push('-- The 78 names on the current rota. needs_review marks the ones the spreadsheet');
L.push("-- leaves genuinely ambiguous ('Matt' could be Matt R or Matt W); the generator");
L.push('-- refuses to schedule anyone still flagged, so these get resolved before use.');
L.push(chunked('people', 'display_name,needs_review,review_note',
  d.roster.map((p) => [q(p.display_name), p.needs_review ? 1 : 0, q(p.review_reason)].join(','))));
L.push('');

// ---- capability -----------------------------------------------------------
L.push('-- Role capability taken from what each person has actually done. This is the');
L.push("-- church's view of who can do what; `willing` is the person's own answer and");
L.push('-- defaults to yes until they say otherwise in self-service. Frequency limits are');
L.push('-- left NULL, meaning "no stated limit yet".');
const prRows = [];
for (const p of d.roster) {
  for (const r of p.roles) {
    prRows.push(
      `(SELECT id FROM people WHERE display_name=${q(p.display_name)}),` +
      `(SELECT id FROM roles WHERE key=${q(r)}),1,1`);
  }
}
L.push(chunked('person_roles', 'person_id,role_id,can_do,willing', prRows));
L.push('');

// ---- pairings -------------------------------------------------------------
// MIN/MAX resolve the ids in SQL because the table CHECKs that the lower id is
// first, and ids are handed out by insertion order — not by name.
L.push('-- Pairs who repeatedly serve together, seeded as a PREFERENCE not a rule: the');
L.push('-- evidence says they choose each other, not that they must be forced together.');
L.push('-- A person may appear in several pairs (Pete serves with both Ruth and Heather),');
L.push('-- which is why this is a table and not a spouse column on people.');
L.push(d.pairs.map((p) =>
  'INSERT OR IGNORE INTO pairings (person_a_id,person_b_id,role_id,mode,strength,note)\n' +
  `SELECT MIN(pa.id,pb.id), MAX(pa.id,pb.id), NULL, ${q('together')}, ${q('prefer')}, ` +
  q(`Served together ${p.times} times in the Sept-Nov rota`) +
  ` FROM people pa, people pb WHERE pa.display_name=${q(p.a)} AND pb.display_name=${q(p.b)};`,
).join('\n'));
L.push('');

// ---- combination rules ----------------------------------------------------
const OVERRIDE = {
  'service_leader|worship_leader': ['amber', 'Allowed but not ideal - stated by the operator'],
};
const EXTRA = [
  ['children_rec_yr5', 'preacher', 'red',
    "A preacher cannot also run children's work - they would be preaching while it is on"],
  ['children_yr6_14', 'preacher', 'red',
    "A preacher cannot also run children's work - they would be preaching while it is on"],
];
const seen = new Set();
const combos = [];
for (const c of d.observed_combinations) {
  const [a, b] = [c.role_a, c.role_b].sort();
  const k = `${a}|${b}`;
  if (seen.has(k)) continue;
  seen.add(k);
  const o = OVERRIDE[k];
  combos.push([a, b, o ? o[0] : 'green', o ? o[1] : `Observed ${c.times} time(s) in the Sept-Nov rota`]);
}
for (const e of EXTRA) {
  const k = `${e[0]}|${e[1]}`;
  if (!seen.has(k)) { seen.add(k); combos.push(e); }
}
L.push('-- Role combination rules for ONE person holding TWO roles at the same service.');
L.push('-- GREEN rows are evidence: the church already does these, and the reason says how');
L.push('-- often. AMBER and RED are the two rules the operator stated explicitly. Note that');
L.push('-- service leader + worship leader is BOTH observed 6 times AND amber - doing a');
L.push('-- thing is not the same as it being ideal. Every other combination is deliberately');
L.push('-- left unset for the vicar to rule on in Settings, rather than invented here.');
L.push(combos.map((r) =>
  'INSERT OR IGNORE INTO role_combinations (role_a_id,role_b_id,verdict,reason)\n' +
  `SELECT MIN(ra.id,rb.id), MAX(ra.id,rb.id), ${q(r[2])}, ${q(r[3])} ` +
  `FROM roles ra, roles rb WHERE ra.key=${q(r[0])} AND rb.key=${q(r[1])};`,
).join('\n'));
L.push('');

fs.writeFileSync(OUT, L.join('\n'));
const stmts = (L.join('\n').match(/;/g) || []).length;
console.log(`wrote 0002_seed.sql — ${stmts} statements`);
console.log(`roles ${ROLES.length} | types ${TYPES.length} | rooms 4 | people ${d.roster.length} | ` +
  `capability ${prRows.length} | pairings ${d.pairs.length} | combinations ${combos.length}`);
console.log('verdicts:', JSON.stringify(combos.reduce((a, c) => ((a[c[2]] = (a[c[2]] || 0) + 1), a), {})));
