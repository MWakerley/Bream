/**
 * A small .xlsx writer, for handing a rota or a list of attendees to somebody
 * who lives in Excel.
 *
 * Written here rather than pulled in: the libraries that do this are built for
 * Node, drag in streams and file-system shims, and are larger than everything
 * else in this Worker put together. An .xlsx is only a zip of a few XML files,
 * and this needs one sheet shape — a title, a header row, rows of text — so the
 * whole format fits on a page.
 *
 * The zip is STORED, not compressed. A rota is a few kilobytes of XML either
 * way, and leaving compression out means no deflate implementation to carry.
 */

export interface SheetColumn {
  header: string;
  /** In Excel's own units, roughly characters. */
  width: number;
}

export interface Sheet {
  name: string;
  /** A title row above the header, e.g. "Bream Church rota — Oct to Dec 2026". */
  title?: string;
  columns: SheetColumn[];
  /** Cells as text. A newline inside a cell becomes a line break in Excel. */
  rows: (string | number | null)[][];
  /** Row indexes (into `rows`) to shade, e.g. services missing a critical role. */
  highlight?: Set<number>;
}

// Style indexes into cellXfs below.
const S_BODY = 1;
const S_HEAD = 2;
const S_TITLE = 3;
const S_ALT = 4;
const S_HIGHLIGHT = 5;

